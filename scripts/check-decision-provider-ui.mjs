import assert from 'node:assert/strict';
import { chromium } from 'playwright';

const browser = await chromium.launch({ channel: process.env.AUTOJEV_BROWSER_CHANNEL || undefined, headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1260, height: 800 }, locale: 'zh-CN' });
  page.setDefaultTimeout(5000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(process.env.AUTOJEV_PREVIEW_URL || 'http://127.0.0.1:1420');
  await page.locator('.settings-trigger').click();
  await page.getByRole('button', { name: '网关与路由', exact: true }).click();
  const provider = page.locator('#decision-provider');
  const model = page.getByLabel('决策模型 ID');
  const key = page.getByLabel('决策密钥');
  assert.match(await provider.innerText(), /OpenRouter/);
  await provider.click();
  await page.getByRole('option', { name: 'ZenMux' }).click();
  assert.equal(await model.inputValue(), 'typesafe/jev-1.13');
  assert.equal(await key.inputValue(), '');
  assert.equal(await page.getByRole('button', { name: '保存决策模型' }).isDisabled(), true);
  assert.equal(await page.getByRole('button', { name: '测试', exact: true }).isDisabled(), true);
  await model.fill('typesafe/jev-custom');
  assert.equal(await model.inputValue(), 'typesafe/jev-custom');
  await key.fill('fixture-zenmux-key');
  await page.getByRole('button', { name: '保存决策模型' }).click();
  await page.getByRole('status').filter({ hasText: '已保存' }).waitFor();
  await page.keyboard.press('Escape');
  await page.locator('.settings-trigger').click();
  assert.match(await provider.innerText(), /ZenMux/);
  assert.equal(await model.inputValue(), 'typesafe/jev-custom');
  if (process.env.AUTOJEV_SCREENSHOT_PATH) await page.screenshot({ path: process.env.AUTOJEV_SCREENSHOT_PATH });
  await provider.click();
  await page.getByRole('option', { name: 'ZenMux' }).click();
  assert.equal(await model.inputValue(), 'typesafe/jev-custom');
  await provider.click();
  await page.getByRole('option', { name: 'OpenRouter' }).click();
  assert.equal(await model.inputValue(), '~typesafe/jev-latest');
  assert.equal(await key.inputValue(), '');
  assert.equal(await page.getByRole('button', { name: '保存决策模型' }).isDisabled(), true);
  await key.fill('temporary-key');
  await provider.click();
  await page.getByRole('option', { name: 'ZenMux' }).click();
  assert.equal(await model.inputValue(), 'typesafe/jev-1.13');
  assert.equal(await key.inputValue(), '');
  assert.equal(await page.getByRole('button', { name: '保存决策模型' }).isDisabled(), false);
  assert.equal(await page.getByLabel('决策地址').count(), 0);
  await page.keyboard.press('Escape');
  const bridgeUrl = await page.evaluate(() => performance.getEntriesByType('resource').find(entry => entry.name.includes('/src/lib/bridge.ts'))?.name);
  assert.ok(bridgeUrl);
  await page.evaluate(async url => {
    const bridge = await import(url);
    const snapshot = await bridge.getSnapshot();
    await bridge.savePolicy({ ...snapshot.policy, decision_provider: 'openrouter', jev_endpoint: 'https://custom.example/api/alpha/decisions', jev_model: 'custom-decision-model' }, 'fixture-custom-key');
  }, bridgeUrl);
  await page.locator('.settings-trigger').click();
  await page.getByRole('tab', { name: '网关设置', exact: true }).click();
  await page.getByRole('button', { name: '保存网关设置' }).click();
  await page.getByRole('status').filter({ hasText: '已保存' }).waitFor();
  await page.keyboard.press('Escape');
  await page.locator('.settings-trigger').click();
  assert.match(await provider.innerText(), /OpenRouter/);
  assert.equal(await model.inputValue(), 'custom-decision-model');
  await page.getByRole('button', { name: '保存决策模型' }).click();
  await page.getByRole('status').filter({ hasText: '已保存' }).waitFor();
  const savedEndpoint = await page.evaluate(async url => (await (await import(url)).getSnapshot()).policy.jev_endpoint, bridgeUrl);
  assert.equal(savedEndpoint, 'https://custom.example/api/alpha/decisions');
  assert.deepEqual(errors, []);
  console.log('decision provider draft and reopen passed');
} finally {
  await browser.close();
}
