import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const artifacts=process.env.AUTOJEV_ARTIFACT_DIR || join(tmpdir(),'autojev-availability');
await mkdir(artifacts,{recursive:true});
const browser=await chromium.launch({channel:process.env.AUTOJEV_BROWSER_CHANNEL || undefined,headless:true});
try {
const page=await browser.newPage({viewport:{width:1260,height:800},locale:'zh-CN'});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.env.AUTOJEV_PREVIEW_URL || 'http://localhost:1420');
await page.locator('.settings-trigger').click();
await page.getByRole('button',{name:'网关与路由',exact:true}).click();
await page.getByLabel('Jev 模型 ID').fill('jev-test');
await page.getByRole('button',{name:'保存 Jev 设置',exact:true}).click();
await page.getByRole('status').filter({hasText:'已保存'}).waitFor();
await page.getByRole('tab',{name:'网关设置',exact:true}).click();
await page.getByLabel('单次请求最多尝试次数').fill('6');
await page.getByRole('button',{name:'保存网关设置',exact:true}).click();
await page.locator('.settings-body').evaluate(el=>el.scrollTop=0);
await page.screenshot({path:join(artifacts,'gateway-settings.png')});
await page.keyboard.press('Escape');
await page.locator('.settings-trigger').click();
assert.equal(await page.getByLabel('Jev 模型 ID').inputValue(),'jev-test');
await page.getByRole('tab',{name:'网关设置',exact:true}).click();
assert.equal(await page.getByLabel('单次请求最多尝试次数').inputValue(),'6');
await page.keyboard.press('Escape');
await page.getByRole('button',{name:'路由',exact:true}).click();
await page.getByRole('button',{name:'添加路由',exact:true}).click();
await page.getByPlaceholder('auto').fill('smart');
await page.locator('.route-dialog-form .search-select-trigger').first().click();
await page.getByRole('option',{name:'均衡',exact:true}).click();
await page.locator('.route-decision-settings').waitFor();
assert.ok((await page.locator('.route-decision-settings').innerText()).includes('优先使用本地模型'));
assert.equal(await page.getByLabel('Jev endpoint').count(),0);
await page.locator('.modal-backdrop').evaluate(el=>Promise.all(el.getAnimations().map(a=>a.finished)));
await page.screenshot({path:join(artifacts,'smart-route.png')});
await page.getByRole('button',{name:'添加模型',exact:true}).click();
await page.locator('.route-model-row .search-select-trigger').click();
await page.getByRole('option',{name:/Qwen 3 Coder Flash/}).click();
await page.getByRole('button',{name:'保存路由',exact:true}).click();
await page.getByRole('button',{name:'编辑路由',exact:true}).click();
assert.equal(await page.getByPlaceholder('auto').inputValue(),'smart');
await page.locator('.route-decision-settings').waitFor();
assert.deepEqual(errors,[]);
console.log(JSON.stringify({result:'settings save/reopen and automatic route preferences passed',errors}));
} finally { await browser.close(); }
